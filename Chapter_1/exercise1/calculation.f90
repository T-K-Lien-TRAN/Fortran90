PROGRAM CALCULATION
! Calculate the sum, difference, product and quotient of two numbers A and B
REAL A, B, SUM, DIFF, PRODUCT, QUOTIENT
READ*, A, B
SUM = A + B
DIFF = A - B
PRODUCT = A * B
QUOTIENT = A/B
PRINT*, 'The sum, difference, product and quotient of two numbers A and B, respectively:', SUM, DIFF, PRODUCT, QUOTIENT
END PROGRAM CALCULATION
